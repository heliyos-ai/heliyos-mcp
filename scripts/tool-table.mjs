#!/usr/bin/env node
/**
 * Renders the README tool table from listToolSpecs(), grouped by resource.
 *
 *   npm run readme:tools            rewrites the section in README.md (builds first)
 *   npm run readme:tools -- --check exits 1 when README.md is out of date
 *
 * The section sits between TOOLS_START and TOOLS_END. tests/readme.test.ts
 * renders the same table from src and fails when README.md drifts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The README marker that opens the generated tool table. */
export const TOOLS_START = "<!-- tools:start (generated by scripts/tool-table.mjs; do not edit) -->";
/** The README marker that closes the generated tool table. */
export const TOOLS_END = "<!-- tools:end -->";

/** Resource groups in reading order. The first group whose pattern matches a tool name claims it. */
export const GROUPS = [
  { title: "Records", pattern: /^heliyos_records_(list|get|create|update|delete|lookup|enrich)$/ },
  { title: "Timeline and activity", pattern: /^heliyos_(records_timeline|records_events|interactions_\w+)$/ },
  { title: "Workspace, objects and fields", pattern: /^heliyos_(organization|objects|fields)_\w+$/ },
  { title: "Notes", pattern: /^heliyos_notes_\w+$/ },
  { title: "Tasks", pattern: /^heliyos_tasks_\w+$/ },
  { title: "Scouts and signals", pattern: /^heliyos_(scouts|companies_scouts|signals)_\w+$/ },
  { title: "Ask, runs and reviews", pattern: /^heliyos_(ask|runs_\w+|reviews_\w+)$/ },
  { title: "Workers, triggers and tools", pattern: /^heliyos_(workers_\w+|triggers_list)$/ },
  { title: "Knowledge base and files", pattern: /^heliyos_(knowledge|files)_\w+$/ },
  { title: "Watchlist", pattern: /^heliyos_(watchlist_get|companies_watch|companies_unwatch)$/ },
  { title: "Labels", pattern: /^heliyos_labels_\w+$/ },
  { title: "Team", pattern: /^heliyos_team_members_\w+$/ },
  { title: "Notification settings", pattern: /^heliyos_notification_settings_\w+$/ },
  { title: "Usage", pattern: /^heliyos_usage_\w+$/ },
];

const kindOf = ({ annotations: a }) => (a.readOnlyHint ? "read" : a.destructiveHint ? "destructive" : "write");
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

/**
 * Markdown for the stable tools plus the experimental extras.
 * `stable` and `experimental` are listToolSpecs({experimental:false|true}).
 */
export function renderToolTable(stable, experimental) {
  const stableNames = new Set(stable.map((t) => t.name));
  const groups = GROUPS.map((g) => ({ ...g, tools: [] }));
  for (const tool of experimental) {
    const group = groups.find((g) => g.pattern.test(tool.name));
    if (!group) throw new Error(`No README group claims ${tool.name}; add it to GROUPS in scripts/tool-table.mjs`);
    group.tools.push(tool);
  }

  const extra = experimental.length - stable.length;
  const lines = [
    `${stable.length} tools by default, and ${extra} more with \`HELIYOS_MCP_EXPERIMENTAL=1\`. ` +
      "Kind is read (no changes), write (creates or updates) or destructive (deletes or removes).",
  ];
  for (const group of groups) {
    if (group.tools.length === 0) continue;
    lines.push("", `#### ${group.title}`, "", "| Tool | What it does | Kind |", "| --- | --- | --- |");
    for (const tool of group.tools) {
      const flag = stableNames.has(tool.name) ? "" : " (experimental)";
      lines.push(`| \`${tool.name}\` | ${cell(tool.title)}${flag} | ${kindOf(tool)} |`);
    }
  }
  return lines.join("\n");
}

/** The generated section of a README, without its markers. */
export function readToolSection(readme) {
  const start = readme.indexOf(TOOLS_START);
  const end = readme.indexOf(TOOLS_END);
  if (start < 0 || end < start) throw new Error("README.md has no tool table markers");
  return readme.slice(start + TOOLS_START.length, end).trim();
}

/** README text with the section replaced by `table`. */
export function replaceToolSection(readme, table) {
  const start = readme.indexOf(TOOLS_START);
  const end = readme.indexOf(TOOLS_END);
  if (start < 0 || end < start) throw new Error("README.md has no tool table markers");
  return `${readme.slice(0, start + TOOLS_START.length)}\n${table}\n${readme.slice(end)}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = new URL("..", import.meta.url);
  const built = new URL("dist/src/index.js", root);
  let listToolSpecs;
  try {
    ({ listToolSpecs } = await import(pathToFileURL(fileURLToPath(built)).href));
  } catch {
    process.stderr.write("tool-table: dist/src/index.js is missing; run `npm run build` first\n");
    process.exit(1);
  }
  const readmePath = fileURLToPath(new URL("README.md", root));
  const readme = readFileSync(readmePath, "utf8");
  const table = renderToolTable(listToolSpecs({ experimental: false }), listToolSpecs({ experimental: true }));
  const next = replaceToolSection(readme, table);
  if (process.argv.includes("--check")) {
    if (next !== readme) {
      process.stderr.write("README.md tool table is out of date; run `npm run readme:tools`\n");
      process.exit(1);
    }
    process.stdout.write("README.md tool table is up to date\n");
  } else if (next !== readme) {
    writeFileSync(readmePath, next);
    process.stdout.write("README.md tool table updated\n");
  } else {
    process.stdout.write("README.md tool table unchanged\n");
  }
}
