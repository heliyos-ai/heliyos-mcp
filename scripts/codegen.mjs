#!/usr/bin/env node
/**
 * Generates src/client/generated.ts (zod v4 schemas + request metadata per
 * operationId) and src/version.ts from src/client/openapi/{platform,auth}.json
 * and package.json.
 *
 * The output is deterministic (no timestamps, source order preserved), so
 * running it twice yields identical files. tests/codegen.test.ts asserts the
 * committed generated.ts matches `generate()`.
 *
 * Supported JSON Schema subset (everything the Heliyos route registry emits):
 * type string|number|integer|boolean|array|object (or a type array), enum,
 * nullable, required, properties, additionalProperties (bool or schema),
 * anyOf/oneOf, items, minLength/maxLength/pattern, minimum/maximum,
 * minItems/maxItems, format email, description. `default` is not applied
 * client-side (the server owns defaults). `date-time` stays a plain string
 * because the server accepts ISO dates without a time part. `$ref` and
 * `allOf` are rejected loudly rather than silently mistyped.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SERVICES = ["platform", "auth"];
const METHODS = ["get", "post", "put", "patch", "delete"];
const OUTPUT = resolve(root, "src/client/generated.ts");
const VERSION_OUTPUT = resolve(root, "src/version.ts");

/**
 * The package ships only the operations its tools and resources call. Every other
 * operation of the public OpenAPI documents is left out of generated.ts, so the
 * published client exposes exactly the API surface the MCP server uses.
 */
const CALLER_DIRS = ["src/tools"];
const CALLER_FILES = ["src/resources.ts"];
const CALL_PATTERN = /callOperation\(\s*[^,()]+,\s*"([A-Za-z_$][\w$]*)"/g;

function tsFilesUnder(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const file = join(dir, name);
    if (statSync(file).isDirectory()) out.push(...tsFilesUnder(file));
    else if (name.endsWith(".ts")) out.push(file);
  }
  return out.sort();
}

/** Sorted operationIds the tools and resources call, read from the source. */
export function usedOperationIds(base = root) {
  const files = [...CALLER_DIRS.flatMap((d) => tsFilesUnder(resolve(base, d))), ...CALLER_FILES.map((f) => resolve(base, f))];
  const ids = new Set();
  for (const file of files) {
    for (const match of readFileSync(file, "utf8").matchAll(CALL_PATTERN)) ids.add(match[1]);
  }
  return [...ids].sort();
}

const HEADER = `// AUTO-GENERATED by scripts/codegen.mjs from src/client/openapi/{platform,auth}.json.
// Do not edit by hand: run \`npm run sync-openapi && npm run codegen\`.
/* eslint-disable */
`;

const str = (value) => JSON.stringify(value);
const shapeOf = (entries) => (entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`);

/** Builds the zod expression for one JSON schema node. `where` names the node in errors. */
function zodFor(schema, where) {
  if (schema === undefined || schema === null || schema === true) return "z.unknown()";
  if (typeof schema !== "object") throw new Error(`${where}: unsupported schema ${str(schema)}`);
  if (schema.$ref) throw new Error(`${where}: $ref is not supported by codegen (${schema.$ref})`);
  if (schema.allOf) throw new Error(`${where}: allOf is not supported by codegen`);

  let expr;
  const union = schema.anyOf ?? schema.oneOf;
  if (union) {
    const members = union.map((member, i) => zodFor(member, `${where}.anyOf[${i}]`));
    expr = members.length === 1 ? members[0] : `z.union([${members.join(", ")}])`;
  } else if (Array.isArray(schema.type)) {
    const nonNull = schema.type.filter((t) => t !== "null");
    const members = nonNull.map((t) => zodFor({ ...schema, type: t, description: undefined }, where));
    expr = members.length === 1 ? members[0] : `z.union([${members.join(", ")}])`;
    if (schema.type.includes("null")) expr += ".nullable()";
  } else if (Array.isArray(schema.enum)) {
    expr = zodEnum(schema.enum, where);
  } else {
    expr = zodForType(schema, where);
  }

  if (schema.nullable === true) expr += ".nullable()";
  if (typeof schema.description === "string" && schema.description.length > 0) {
    expr += `.describe(${str(schema.description)})`;
  }
  return expr;
}

function zodEnum(values, where) {
  if (values.length === 0) throw new Error(`${where}: empty enum`);
  if (values.every((v) => typeof v === "string")) return `z.enum(${str(values)})`;
  const literals = values.map((v) => (v === null ? "z.null()" : `z.literal(${str(v)})`));
  return literals.length === 1 ? literals[0] : `z.union([${literals.join(", ")}])`;
}

function zodForType(schema, where) {
  switch (schema.type) {
    case "string": {
      let expr = schema.format === "email" ? "z.email()" : "z.string()";
      if (Number.isInteger(schema.minLength)) expr += `.min(${schema.minLength})`;
      if (Number.isInteger(schema.maxLength)) expr += `.max(${schema.maxLength})`;
      if (typeof schema.pattern === "string") expr += `.regex(new RegExp(${str(schema.pattern)}))`;
      return expr;
    }
    case "number":
    case "integer": {
      let expr = schema.type === "integer" ? "z.number().int()" : "z.number()";
      if (typeof schema.minimum === "number") expr += `.min(${schema.minimum})`;
      if (typeof schema.maximum === "number") expr += `.max(${schema.maximum})`;
      return expr;
    }
    case "boolean":
      return "z.boolean()";
    case "array": {
      let expr = `z.array(${zodFor(schema.items, `${where}[]`)})`;
      if (Number.isInteger(schema.minItems)) expr += `.min(${schema.minItems})`;
      if (Number.isInteger(schema.maxItems)) expr += `.max(${schema.maxItems})`;
      return expr;
    }
    case "object":
      return zodObject(schema, where);
    case undefined:
      return schema.properties ? zodObject(schema, where) : "z.unknown()";
    default:
      throw new Error(`${where}: unsupported type ${str(schema.type)}`);
  }
}

function zodObject(schema, where) {
  const required = new Set(schema.required ?? []);
  const entries = Object.entries(schema.properties ?? {}).map(([key, prop]) => {
    const value = zodFor(prop, `${where}.${key}`);
    return `${str(key)}: ${required.has(key) ? value : `${value}.optional()`}`;
  });
  const shape = shapeOf(entries);
  const extra = schema.additionalProperties;
  if (extra === false) return `z.strictObject(${shape})`;
  if (extra === undefined || extra === true) return `z.looseObject(${shape})`;
  return `z.object(${shape}).catchall(${zodFor(extra, `${where}.*`)})`;
}

/** Builds a strict object schema from OpenAPI parameters of one location. */
function zodParams(parameters, location, where) {
  const entries = parameters
    .filter((p) => p.in === location)
    .map((p) => {
      const schema = p.description && p.schema && !p.schema.description ? { ...p.schema, description: p.description } : p.schema;
      const value = zodFor(schema, `${where}.${location}.${p.name}`);
      const required = location === "path" || p.required === true;
      return `${str(p.name)}: ${required ? value : `${value}.optional()`}`;
    });
  return `z.strictObject(${shapeOf(entries)})`;
}

function zodBody(requestBody, where) {
  if (!requestBody) return "z.undefined()";
  const content = requestBody.content ?? {};
  const json = content["application/json"];
  if (!json) throw new Error(`${where}: only application/json request bodies are supported (got ${Object.keys(content).join(", ")})`);
  const expr = zodFor(json.schema, `${where}.body`);
  return requestBody.required === true ? expr : `${expr}.optional()`;
}

function loadSpec(service) {
  const file = resolve(root, `src/client/openapi/${service}.json`);
  let doc;
  try {
    doc = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new Error(`codegen: cannot read ${file} (${err.message}). Run \`npm run sync-openapi\` first.`);
  }
  if (!doc.paths || typeof doc.paths !== "object") throw new Error(`codegen: ${file} has no paths`);
  return doc;
}

/**
 * Returns the full text of src/client/generated.ts. Pure: reads inputs, writes nothing.
 * `renamed` collects operationIds that were prefixed to resolve cross-service collisions.
 */
export function generate(renamed = []) {
  const seen = new Map();
  const seenInService = new Set();
  const blocks = [];
  const used = new Set(usedOperationIds());
  const emitted = new Set();

  for (const service of SERVICES) {
    const doc = loadSpec(service);
    for (const [path, item] of Object.entries(doc.paths)) {
      const shared = Array.isArray(item.parameters) ? item.parameters : [];
      for (const method of METHODS) {
        const op = item[method];
        if (!op) continue;
        const id = op.operationId;
        const where = `${service} ${method.toUpperCase()} ${path}`;
        if (typeof id !== "string" || !/^[A-Za-z_$][\w$]*$/.test(id)) {
          throw new Error(`codegen: ${where} has a missing or non-identifier operationId (${str(id)})`);
        }
        if (seenInService.has(`${service}:${id}`)) throw new Error(`codegen: duplicate operationId ${id} within ${service} (${where})`);
        seenInService.add(`${service}:${id}`);
        //  Cross-service collisions (e.g. getHealth in both services): the first
        //  service keeps the bare id, later ones get a service prefix.
        const key = seen.has(id) ? `${service}${id[0].toUpperCase()}${id.slice(1)}` : id;
        if (seen.has(key)) throw new Error(`codegen: operationId ${key} for ${where} collides with ${seen.get(key)}`);
        if (key !== id) renamed.push(`${id} (${where}) -> ${key}`);
        seen.set(key, where);
        // Only the operations the tools and resources call are emitted.
        if (!used.has(key)) continue;
        emitted.add(key);

        const parameters = [...shared, ...(op.parameters ?? [])];
        for (const p of parameters) {
          if (p.$ref) throw new Error(`codegen: ${where} uses a parameter $ref, which is not supported`);
          if (p.in !== "path" && p.in !== "query") throw new Error(`codegen: ${where} has an unsupported ${p.in} parameter ${p.name}`);
        }
        const templateNames = [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
        const declared = parameters.filter((p) => p.in === "path").map((p) => p.name);
        for (const name of templateNames) {
          if (!declared.includes(name)) throw new Error(`codegen: ${where} path param {${name}} is not declared`);
        }

        blocks.push(
          [
            `  ${key}: {`,
            `    operationId: ${str(id)},`,
            `    service: ${str(service)},`,
            `    method: ${str(method.toUpperCase())},`,
            `    path: ${str(path)},`,
            `    pathParams: ${str(templateNames)},`,
            `    params: ${zodParams(parameters, "path", where)},`,
            `    query: ${zodParams(parameters, "query", where)},`,
            `    body: ${zodBody(op.requestBody, where)},`,
            `  },`,
          ].join("\n")
        );
      }
    }
  }

  const missing = [...used].filter((id) => !emitted.has(id)).sort();
  if (missing.length > 0) {
    throw new Error(`codegen: the tools call operation(s) that no OpenAPI document defines: ${missing.join(", ")}`);
  }

  return `${HEADER}import * as z from "zod/v4";

/** The HTTP methods the Heliyos API uses. */
export type HttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";

/** One API operation: its id, method, path template and the zod schemas for its path params, query and body. */
export interface OperationDefinition {
  readonly operationId: string;
  readonly service: "platform" | "auth";
  readonly method: HttpMethod;
  /** Path template, e.g. "/v1/platform/tasks/{id}". */
  readonly path: string;
  /** Names of the {placeholders} in \`path\`, in order. */
  readonly pathParams: readonly string[];
  readonly params: z.ZodType;
  readonly query: z.ZodType;
  /** z.undefined() when the operation takes no body. */
  readonly body: z.ZodType;
}

/** Every operation the tools call, keyed by operationId. Generated from the bundled OpenAPI documents. */
export const operations = {
${blocks.join("\n")}
} as const satisfies Record<string, OperationDefinition>;

/** The type of the operation table. */
export type Operations = typeof operations;
/** A valid operationId. */
export type OperationId = keyof Operations;

/** Response \`data\` is not described by the OpenAPI documents yet, so it is \`unknown\`. */
export type OperationData<_K extends OperationId> = unknown;
`;
}

/** src/version.ts for a package.json; scripts/set-version.mjs writes it too. */
export function versionModule(pkg) {
  return `${HEADER}/** The npm package name, for the User-Agent header. */\nexport const PACKAGE_NAME = ${str(pkg.name)};\n/** The package version, for the User-Agent header and the MCP server info. */\nexport const PACKAGE_VERSION = ${str(pkg.version)};\n`;
}

function generateVersion() {
  return versionModule(JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")));
}

function writeIfChanged(file, content) {
  let current;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = undefined;
  }
  if (current === content) return false;
  writeFileSync(file, content);
  return true;
}

function main() {
  const renamed = [];
  const outputs = [
    [OUTPUT, generate(renamed)],
    [VERSION_OUTPUT, generateVersion()],
  ];
  for (const [file, content] of outputs) {
    const changed = writeIfChanged(file, content);
    console.log(`codegen: ${changed ? "wrote" : "unchanged"} ${file}`);
  }
  for (const line of renamed) console.log(`codegen: renamed colliding operationId ${line}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
